#!/usr/bin/env python3
"""Generates src/tokenizer/unicode_tables.rs.

The BPE pre-tokenizers split text on Unicode general categories. The Rust
standard library exposes numbers and whitespace but not letters or
punctuation, so those two are generated here as sorted range tables.

Usage:
    python3 tools/gen_unicode.py > src/tokenizer/unicode_tables.rs
"""

import unicodedata


def ranges(prefix):
    """Returns the inclusive code point ranges whose category starts with prefix."""
    found = []
    start = None
    for code_point in range(0x110000):
        inside = unicodedata.category(chr(code_point)).startswith(prefix)
        if inside and start is None:
            start = code_point
        elif not inside and start is not None:
            found.append((start, code_point - 1))
            start = None
    if start is not None:
        found.append((start, 0x10FFFF))
    return found


def table(name, doc, prefix):
    """Formats one category as a Rust static."""
    pairs = ranges(prefix)
    lines = [f"/// {doc}", "#[rustfmt::skip]", f"pub(super) static {name}: [(u32, u32); {len(pairs)}] = ["]
    for i in range(0, len(pairs), 6):
        row = ", ".join(f"(0x{low:x}, 0x{high:x})" for low, high in pairs[i : i + 6])
        lines.append(f"    {row},")
    lines.append("];")
    return "\n".join(lines)


def main():
    print("//! Unicode general category tables.")
    print("//!")
    print("//! Generated by tools/gen_unicode.py. Do not edit by hand.")
    print(f"//! Unicode version {unicodedata.unidata_version}.")
    print("//!")
    print("//! Each table is a sorted list of inclusive code point ranges.")
    print()
    print(table("LETTER", "Code points in general category L (letters).", "L"))
    print()
    print(table("PUNCTUATION", "Code points in general category P (punctuation).", "P"))


if __name__ == "__main__":
    main()

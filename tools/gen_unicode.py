#!/usr/bin/env python3
"""Generates src/tokenizer/unicode_tables.rs.

The BPE pre-tokenizers split text on Unicode general categories: letters
and their kinds (\\p{L}, \\p{Lu}, \\p{Ll}), marks, numbers, punctuation and
symbols. The Rust standard library exposes few of these, so this writes one
table that gives the general category of every code point.

The table lists runs of code points that share a category. Each entry packs
the first code point of a run, shifted left 5 bits, with the number of its
category in the low 5 bits. A lookup is a binary search for the last run
that starts at or before the code point.

Usage:
    python3 tools/gen_unicode.py > src/tokenizer/unicode_tables.rs
"""

import unicodedata

# Every general category, in the order their numbers are given.
CATEGORIES = [
    "Cc", "Cf", "Cn", "Co", "Cs",
    "Ll", "Lm", "Lo", "Lt", "Lu",
    "Mc", "Me", "Mn",
    "Nd", "Nl", "No",
    "Pc", "Pd", "Pe", "Pf", "Pi", "Po", "Ps",
    "Sc", "Sk", "Sm", "So",
    "Zl", "Zp", "Zs",
]

# What each category is, for the comments of the generated enum.
NAMES = {
    "Cc": "control", "Cf": "format", "Cn": "unassigned", "Co": "private use",
    "Cs": "surrogate", "Ll": "lowercase letter", "Lm": "modifier letter",
    "Lo": "other letter", "Lt": "titlecase letter", "Lu": "uppercase letter",
    "Mc": "spacing mark", "Me": "enclosing mark", "Mn": "nonspacing mark",
    "Nd": "decimal number", "Nl": "letter number", "No": "other number",
    "Pc": "connector punctuation", "Pd": "dash punctuation",
    "Pe": "close punctuation", "Pf": "final punctuation",
    "Pi": "initial punctuation", "Po": "other punctuation",
    "Ps": "open punctuation", "Sc": "currency symbol",
    "Sk": "modifier symbol", "Sm": "math symbol", "So": "other symbol",
    "Zl": "line separator", "Zp": "paragraph separator",
    "Zs": "space separator",
}


def runs():
    """Returns (first code point, category) for each run of one category."""
    found = []
    previous = None
    for code_point in range(0x110000):
        category = unicodedata.category(chr(code_point))
        if category != previous:
            found.append((code_point, category))
            previous = category
    return found


def main():
    table = runs()
    print("//! The Unicode general category of every code point.")
    print("//!")
    print("//! Generated by tools/gen_unicode.py. Do not edit by hand.")
    print(f"//! Unicode version {unicodedata.unidata_version}.")
    print()
    print("/// A Unicode general category.")
    print("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    print("#[repr(u8)]")
    print("pub(super) enum Category {")
    for number, category in enumerate(CATEGORIES):
        print(f"    /// {NAMES[category].capitalize()}.")
        print(f"    {category} = {number},")
    print("}")
    print()
    print("/// Every category, indexed by its number.")
    names = ", ".join(f"Category::{category}" for category in CATEGORIES)
    print(f"pub(super) const BY_NUMBER: [Category; {len(CATEGORIES)}] = [{names}];")
    print()
    print("/// Runs of code points with one category: the first code point shifted")
    print("/// left 5 bits, plus the category's number. Sorted by code point.")
    print("#[rustfmt::skip]")
    print(f"pub(super) static RUNS: [u32; {len(table)}] = [")
    entries = [f"0x{(start << 5) | CATEGORIES.index(category):x}" for start, category in table]
    for i in range(0, len(entries), 10):
        print("    " + ", ".join(entries[i : i + 10]) + ",")
    print("];")


if __name__ == "__main__":
    main()

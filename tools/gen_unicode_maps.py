#!/usr/bin/env python3
"""Writes src/tokenizer/unicode_maps.rs from llama.cpp's Unicode tables.

    python3 tools/gen_unicode_maps.py path/to/llama.cpp > src/tokenizer/unicode_maps.rs

WordPiece tokenizers lowercase text and strip accents with llama.cpp's own
tables: a simple lowercase map, and for each decomposable character the
first code point of its decomposition. Taking the tables from llama.cpp's
src/unicode-data.cpp makes both engines normalize the same way.

Both tables are stored compactly. Lowercase mappings come in runs, such as
A to Z or the alternating capitals of Latin Extended-A, so each run is one
entry: its first code point, how many, the step between them and the
offset to add. Decompositions are ranges that map to one code point.
"""

import pathlib
import re
import sys


def entries(text, name):
    """The numbers of each {0x.., 0x..} entry of the C++ table `name`."""
    start = text.index(name)
    end = text.index("};", start)
    return [
        [int(number, 16) for number in re.findall(r"0x([0-9A-Fa-f]+)", line)]
        for line in text[start:end].splitlines()
        if line.startswith("{0x")
    ]


def lowercase_runs(pairs):
    """Groups (code point, lowercase) pairs into (first, count, step, offset)."""
    runs = []
    for upper, lower in pairs:
        offset = lower - upper
        if runs:
            first, count, step, run_offset = runs[-1]
            last = first + (count - 1) * step
            if run_offset == offset and count == 1 and upper - first in (1, 2):
                runs[-1] = (first, 2, upper - first, offset)
                continue
            if run_offset == offset and count > 1 and upper - last == step:
                runs[-1] = (first, count + 1, step, offset)
                continue
        runs.append((upper, 1, 1, offset))
    return runs


def main():
    root = pathlib.Path(sys.argv[1])
    text = (root / "src" / "unicode-data.cpp").read_text()
    lowercase = sorted(tuple(entry) for entry in entries(text, "unicode_map_lowercase ="))
    nfd = [tuple(entry) for entry in entries(text, "unicode_ranges_nfd =")]
    runs = lowercase_runs(lowercase)

    # Check the runs expand to exactly the table.
    expanded = sorted(
        (first + index * step, first + index * step + offset)
        for first, count, step, offset in runs
        for index in range(count)
    )
    assert expanded == lowercase, "lowercase runs do not round trip"
    assert all(last - first < 1 << 11 and target < 1 << 21 for first, last, target in nfd)

    out = sys.stdout
    out.write("//! Generated by tools/gen_unicode_maps.py from llama.cpp's\n")
    out.write("//! src/unicode-data.cpp. Do not edit by hand.\n\n")
    out.write("/// Runs of simple lowercase mappings, sorted: the first code point, how\n")
    out.write("/// many, the step between them, and the offset that lowercases each.\n")
    out.write(f"pub(super) const LOWERCASE: [(u32, u16, u8, i32); {len(runs)}] = [\n")
    for first, count, step, offset in runs:
        out.write(f"    (0x{first:X}, {count}, {step}, {offset}),\n")
    out.write("];\n\n")
    out.write("/// Ranges of characters that decompose, sorted, and the first code point\n")
    out.write("/// of their decomposition: `(first, last - first, target)`, the last\n")
    out.write("/// two packed as `(last - first) << 21 | target`.\n")
    out.write(f"pub(super) const NFD: [(u32, u32); {len(nfd)}] = [\n")
    for first, last, target in nfd:
        out.write(f"    (0x{first:X}, 0x{((last - first) << 21) | target:X}),\n")
    out.write("];\n")


if __name__ == "__main__":
    main()
